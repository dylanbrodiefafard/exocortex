/// Looks up a named color (lowercase).
pub fn lookup(name: &str) -> Option<Rgba> {
    NAMED.binary_search_by(|(n, _)| n.cmp(&name)).ok().map(|i| NAMED[i].1)
}

/// The name of the first named color with exactly these channels, if any (opaque colors only).
pub fn name_of(c: &Rgba) -> Option<&'static str> {
    if !c.is_opaque() {
        return None;
    }
    NAMED.iter().find(|(_, v)| v.r == c.r && v.g == c.g && v.b == c.b).map(|(n, _)| *n)
}
